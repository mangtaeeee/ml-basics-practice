import numpy as np

from sklearn.metrics import (
    confusion_matrix,
    accuracy_score,
    precision_score,
    recall_score,
    f1_score
)


# --------------------------------------------------
# 1. 실제 정답 Label 만들기
# --------------------------------------------------
#
# 0 = 정상
# 1 = 이상
#
# 정상 990건
# 이상 10건
#
# 전체 1000건 중 이상은 1%뿐
#
# 이것이 Class Imbalance(클래스 불균형)
# = 한쪽 클래스가 압도적으로 많은 상태

y_test = np.array(
    [0] * 990 +
    [1] * 10
)


# --------------------------------------------------
# 2. 아주 멍청한 모델을 가정
# --------------------------------------------------
#
# 모델이 모든 데이터를 무조건
# "정상(0)"이라고 예측했다고 가정
#
# 실제로는 AI 모델을 학습시키는 것이 아니라
# Accuracy의 문제점을 보기 위한 실험

prediction = np.array(
    [0] * 1000
)


# --------------------------------------------------
# 3. 데이터 개수 확인
# --------------------------------------------------

print("전체 데이터 :", len(y_test))
print("정상 데이터 :", np.sum(y_test == 0))
print("이상 데이터 :", np.sum(y_test == 1))

print()


# --------------------------------------------------
# 4. Confusion Matrix = 혼동 행렬
# --------------------------------------------------
#
# sklearn 기준
#
# [[TN FP]
#  [FN TP]]
#
# TN = 실제 정상 / 예측 정상
# FP = 실제 정상 / 예측 이상
# FN = 실제 이상 / 예측 정상
# TP = 실제 이상 / 예측 이상

matrix = confusion_matrix(y_test, prediction)

print("===== Confusion Matrix(혼동 행렬) =====")
print(matrix)

print()


# --------------------------------------------------
# 5. Accuracy = 정확도
# --------------------------------------------------
#
# 전체 중 얼마나 맞혔는가?

accuracy = accuracy_score(y_test, prediction)


# --------------------------------------------------
# 6. Precision = 정밀도
# --------------------------------------------------
#
# 모델이 이상이라고 예측한 것 중
# 실제 이상인 비율
#
# 그런데 이번 모델은
# 이상이라고 한 번도 예측하지 않았음
#
# zero_division=0
# → 0으로 나누는 상황이 발생하면
#   에러 대신 0으로 처리

precision = precision_score(
    y_test,
    prediction,
    zero_division=0
)


# --------------------------------------------------
# 7. Recall = 재현율
# --------------------------------------------------
#
# 실제 이상 데이터 중
# 모델이 찾아낸 비율

recall = recall_score(
    y_test,
    prediction,
    zero_division=0
)


# --------------------------------------------------
# 8. F1 Score = F1 점수
# --------------------------------------------------
#
# Precision과 Recall의 균형을 보는 점수

f1 = f1_score(
    y_test,
    prediction,
    zero_division=0
)


# --------------------------------------------------
# 9. 결과 출력
# --------------------------------------------------

print("===== 평가 결과 =====")
print("Accuracy(정확도) :", accuracy)
print("Precision(정밀도) :", precision)
print("Recall(재현율) :", recall)
print("F1 Score(F1 점수) :", f1)